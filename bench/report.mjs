// Render bench/out/results.json as markdown (bench/out/results.md).
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const r = JSON.parse(readFileSync(join(import.meta.dirname, "out", "results.json"), "utf8"));
const { turns, agents, items } = r.params;
const kb = (b) => `${(b / 1024).toFixed(1)} KB`;
const ms = (x) => `${x.toFixed(2)} ms`;
const img = r.image, p = img.perAgent[0], tr = r.transcript, pi = r.pi, mem = r.memory;
const lines = [];
const row = (...c) => lines.push(`| ${c.join(" | ")} |`);

lines.push(`Scenario: ${turns} turns per agent, ${agents} agents, one ${kb(JSON.stringify({ items: new Array(items).fill({ id: 0, name: "record-00-000", score: 50, tags: ["alpha"], note: "lorem ipsum dolor sit amet" }) }).length)} fetch per turn kept in working memory. ${r.params.node} on ${r.params.platform}/${r.params.arch}, ${r.params.date.slice(0, 10)}.`);
lines.push("");
lines.push(`### Disk per agent after ${turns} turns`);
lines.push("");
row("System", "What is stored", "Bytes per agent", "Model context, last request", "Time per turn");
row("---", "---", "---", "---", "---");
row("**Agent image**", `live chain: folded base ${kb(p.lastBase)} + ${p.headSeq - p.baseSeq} deltas; journal of host calls ${kb(p.journal)} (messages stored once)`, `**${kb(p.chainLive + p.journal)}** (${kb(p.cold)} in the cold dir)`, kb(img.modelContextBytes.last), ms(p.msPerTurn) + ` (${img.activationsPerTurn} activations)`);
if (pi) row("Pi Durable 1.4.0", "entries, tasks, documents (store() writes as document revisions), in its SQLite schema", kb(pi.fileBytesPerAgent), "whole transcript", ms(pi.msPerTurn));
row("Transcript, payload kept", "every message inline, as a conversation-level store must to keep the data", kb(tr.keep.fileBytesPerAgent), kb(tr.keep.modelContextBytesLast), ms(tr.keep.msPerTurn));
row("Transcript, payload dropped", "the same without the fetched data (information lost)", kb(tr.drop.fileBytesPerAgent), kb(tr.drop.modelContextBytesLast), ms(tr.drop.msPerTurn));
lines.push("");
lines.push(`Image write amplification: ${kb(p.writtenPerTurn)} of checkpoints per turn, folds included, plus ${kb(p.journalPerTurn)} of journal. Base image with the harness: ${kb(img.baseBytes)}.`);
lines.push("");
lines.push("### Bytes per checkpoint (image)");
lines.push("");
row("Park", "Median", "Max", "n");
row("---", "---", "---", "---");
const names = { "chain:park": "parked on a call (model or tool), delta", "chain:reply": "reply committed, delta", "base:park": "fold while parked, full base", "base:reply": "fold at reply, full base" };
for (const [k, v] of Object.entries(img.checkpointBytes)) row(names[k] ?? k, kb(v.median), kb(v.max), v.n);
lines.push("");
lines.push(`Snapshot write median ${ms(img.snapshotMs)}, commit (SQLite transaction) median ${ms(img.commitMs)}, run inside the heap median ${ms(img.runMs)} per activation.`);
lines.push("");
lines.push(`### Restore time per tier (image, agent after ${turns} turns)`);
lines.push("");
row("Tier", "Resume after the event arrives", "Of which", "Chain loaded");
row("---", "---", "---", "---");
row("Hot (heap live)", ms(img.tiers.hot.restoreMs), "deliver only", "none");
row("Warm (SQLite)", ms(img.tiers.warm.restoreMs), `read ${ms(img.tiers.warm.readMs)}, instantiate ${ms(img.tiers.warm.instantiateMs)}, apply ${ms(img.tiers.warm.applyMs)}`, `${img.tiers.warm.chainLength} deltas, ${kb(img.tiers.warm.chainBytes)}`);
row("Cold (files)", ms(img.tiers.cold.restoreMs), `read ${ms(img.tiers.cold.readMs)}, instantiate ${ms(img.tiers.cold.instantiateMs)}, apply ${ms(img.tiers.cold.applyMs)}`, `${img.tiers.cold.chainLength} deltas, ${kb(img.tiers.cold.chainBytes)}`);
lines.push("");
lines.push("Cold here is local disk; add one object-storage round trip for a real cold tier.");
lines.push("");
lines.push(`### Resident memory per agent (${r.params.memAgents} agents, each after ${mem.turns} turns)`);
lines.push("");
row("Where the agent lives", "Per agent", "Note");
row("---", "---", "---");
row("Image, parked", "0", "storage only");
row("Image, hot (wasm instance restored)", `${kb(mem.image.rssPerAgent)} RSS`, `wasm linear memory ${kb(mem.image.linearBytes)}, engine heap used ${kb(mem.image.heapUsed)}; ${ms(mem.image.instantiateAndRestoreMs)} to instantiate and restore`);
row("Same harness in a V8 context (node:vm)", `${kb(mem.v8vm.jsHeapPerAgent)} V8 heap`, "contexts share one isolate; a real isolate (workerd, Dynamic Workers) adds its own heap and code space");
if (pi) row("Pi Durable, one harness per conversation, open and idle", `${kb(pi.residentPerConversationWhileOpen)} RSS`, "the harness process state dominates (TypeBox, pi-ai, the QuickJS sandbox); many conversations share one harness in practice, so this is not a per-conversation cost");
row("Infinity (claimed)", "~100 KB", "from its in-memory benchmark, not measured here");
lines.push("");
lines.push("### Model context");
lines.push("");
lines.push(`The image sends the conversation window plus handles: first request ${kb(img.modelContextBytes.first)}, median ${kb(img.modelContextBytes.median)}, last ${kb(img.modelContextBytes.last)}. A conversation-level store that keeps the data sends it all: ${kb(tr.keep.modelContextBytesLast)} on the last request. The scripted gateway served ${img.broker.modelCalls} completions and answered ${img.broker.cacheHits} from its content-keyed cache.`);

writeFileSync(join(import.meta.dirname, "out", "results.md"), lines.join("\n") + "\n");
console.log(lines.join("\n"));
